//! Regtest harness.
//!
//! Thin wrapper over `bitcoincore-rpc` for tests that need to mine, fund
//! addresses, and observe the mempool. The compose stack in
//! `deploy/docker/` is expected to be running (`just regtest-up`).
//!
//! This harness is orthogonal to [`crate::TestWallet`] — the wallet has its
//! own view of UTXOs via BDK, while this type talks to bitcoind directly
//! and is the canonical place for "mine N blocks" or "send_to_address"
//! helpers.

use std::str::FromStr;
use std::time::Duration;

use anyhow::{Context, Result};
use bitcoin::{Address, Amount, BlockHash, Network};
use bitcoincore_rpc::{Auth, Client, RpcApi};

/// Connection config for a regtest bitcoind.
#[derive(Debug, Clone)]
pub struct BitcoindConfig {
    /// JSON-RPC endpoint, e.g. `http://127.0.0.1:18443`. Default pulls from
    /// `BITCOIND_RPC_URL` falling back to the docker-compose default.
    pub rpc_url: String,
    /// RPC auth. Default: `user:password` from `BITCOIND_RPC_USER` /
    /// `BITCOIND_RPC_PASS`, falling back to `wick:wick`.
    pub auth: Auth,
    /// Network — must be `Regtest` for test harness use.
    pub network: Network,
}

impl Default for BitcoindConfig {
    fn default() -> Self {
        let rpc_url = std::env::var("BITCOIND_RPC_URL")
            .unwrap_or_else(|_| "http://127.0.0.1:18443".to_owned());
        let user = std::env::var("BITCOIND_RPC_USER").unwrap_or_else(|_| "wick".to_owned());
        let pass = std::env::var("BITCOIND_RPC_PASS").unwrap_or_else(|_| "wick".to_owned());
        Self {
            rpc_url,
            auth: Auth::UserPass(user, pass),
            network: Network::Regtest,
        }
    }
}

/// Typed handle on a regtest bitcoind over JSON-RPC.
#[derive(Debug)]
pub struct Regtest {
    client: Client,
    network: Network,
}

impl Regtest {
    /// Connect with the given config. Does not issue any RPC.
    pub fn connect(cfg: &BitcoindConfig) -> Result<Self> {
        let client = Client::new(&cfg.rpc_url, cfg.auth.clone())
            .with_context(|| format!("bitcoind RPC connect: {}", cfg.rpc_url))?;
        Ok(Self {
            client,
            network: cfg.network,
        })
    }

    /// Connect with defaults pulled from env.
    pub fn default_connect() -> Result<Self> {
        Self::connect(&BitcoindConfig::default())
    }

    /// Wait until bitcoind responds to `getblockchaininfo`; retries with
    /// short backoff up to `timeout`.
    pub async fn wait_ready(&self, timeout: Duration) -> Result<()> {
        let deadline = tokio::time::Instant::now() + timeout;
        loop {
            match self.client.get_blockchain_info() {
                Ok(_) => return Ok(()),
                Err(e) if tokio::time::Instant::now() >= deadline => {
                    return Err(anyhow::anyhow!("bitcoind not ready after {timeout:?}: {e}"));
                }
                Err(_) => tokio::time::sleep(Duration::from_millis(200)).await,
            }
        }
    }

    /// Current tip height.
    pub fn tip_height(&self) -> Result<u32> {
        let info = self.client.get_blockchain_info()?;
        u32::try_from(info.blocks).context("tip height exceeds u32")
    }

    /// Mine `n` blocks to a throwaway address generated by bitcoind itself.
    ///
    /// Returns the list of mined block hashes.
    pub fn mine(&self, n: u64) -> Result<Vec<BlockHash>> {
        let addr = self
            .client
            .get_new_address(Some("testkit-mine"), None)
            .context("get_new_address")?
            .require_network(self.network)
            .map_err(|e| anyhow::anyhow!("address network mismatch: {e}"))?;
        let hashes = self
            .client
            .generate_to_address(n, &addr)
            .context("generate_to_address")?;
        Ok(hashes)
    }

    /// Mine `n` blocks to a specific address (useful for funding a BDK
    /// wallet's coinbase output).
    ///
    /// Coinbase outputs require 100 confirmations before they're spendable.
    pub fn mine_to(&self, n: u64, address: &Address) -> Result<Vec<BlockHash>> {
        Ok(self
            .client
            .generate_to_address(n, address)
            .context("generate_to_address")?)
    }

    /// Send `amount_sat` to `address` from bitcoind's own wallet. Returns
    /// the funding txid.
    pub fn send_to_address(&self, address: &Address, amount_sat: u64) -> Result<bitcoin::Txid> {
        let amount = Amount::from_sat(amount_sat);
        let txid = self
            .client
            .send_to_address(address, amount, None, None, None, None, None, None)
            .context("send_to_address")?;
        Ok(txid)
    }

    /// Wait for the tip to reach `min_height`, polling every 200 ms until
    /// `timeout`.
    pub async fn wait_for_height(&self, min_height: u32, timeout: Duration) -> Result<()> {
        let deadline = tokio::time::Instant::now() + timeout;
        loop {
            let h = self.tip_height()?;
            if h >= min_height {
                return Ok(());
            }
            if tokio::time::Instant::now() >= deadline {
                return Err(anyhow::anyhow!(
                    "tip height {h} < {min_height} after {timeout:?}"
                ));
            }
            tokio::time::sleep(Duration::from_millis(200)).await;
        }
    }

    /// Invalidate a block — used by reorg simulations in later phases.
    pub fn invalidate_block(&self, hash: &BlockHash) -> Result<()> {
        self.client
            .invalidate_block(hash)
            .context("invalidate_block")?;
        Ok(())
    }

    /// Raw handle for tests that need calls not surfaced here.
    #[must_use]
    pub fn client(&self) -> &Client {
        &self.client
    }

    /// Ensure bitcoind has a loaded wallet named `name`; create it if
    /// missing. Regtest environments often boot with no wallet loaded, which
    /// makes `get_new_address` fail.
    pub fn ensure_wallet(&self, name: &str) -> Result<()> {
        if let Ok(list) = self.client.list_wallets() {
            if list.iter().any(|w| w == name) {
                return Ok(());
            }
        }
        // Try load first; create if it doesn't exist on disk.
        if self.client.load_wallet(name).is_err() {
            let _ = self.client.create_wallet(name, None, None, None, None);
        }
        Ok(())
    }
}

/// Parse a regtest-network address from a string.
///
/// Shorthand so tests don't have to handle the network-checked path manually.
pub fn parse_address(s: &str) -> Result<Address> {
    let unchecked = Address::from_str(s).map_err(|e| anyhow::anyhow!("parse address: {e}"))?;
    unchecked
        .require_network(Network::Regtest)
        .map_err(|e| anyhow::anyhow!("address network mismatch: {e}"))
}
